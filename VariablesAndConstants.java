public class VariablesAndConstants {
    public static void main(String[] args) {
       
        //variables

        String name = "Johan";
        System.out.println(name);

        name = "Stiven";
        System.out.println(name);

        //name = 19; Error (no podemos cambiar el tipo de dato de la variable)

        int age = 17;
        System.out.println(age);

        var email = "szuluagapipicano@gmail.com";
        System.out.println(email);
        
        var year = 2026;
        System.out.println(year);

        //Constantes

       final String EMAIL = "szuluagapipicano@gmail.com";
       // EMAIL = "szuluaga@gmail.com"; no se puede modificar una constante
        System.out.println(EMAIL);


    }
} 